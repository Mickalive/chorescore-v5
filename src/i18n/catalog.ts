/**
 * Resolve a locale string, interpolating `{name}` placeholders.
 * Falls back to FR, then to the raw key when a translation is missing so a
 * missing key is visible rather than silently empty.
 */
export function resolveString(
  locale: SupportedLocale,
  key: string,
  params?: Record<string, string | number>,
): string {
  const primary = CATALOG[locale]?.[key];
  const fallback = CATALOG[DEFAULT_LOCALE]?.[key];
  const template = primary ?? fallback ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match,
  );
}

/** Unit short label for the household contribution unit. */
export function unitShortLabel(
  unit: 'minutes' | 'points',
  locale: SupportedLocale,
): string {
  return resolveString(locale, unit === 'points' ? 'unit.pointsShort' : 'unit.minutesShort');
}
